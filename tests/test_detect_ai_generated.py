#!/usr/bin/env python3
"""Test script for detect_ai_generated.py"""

import tempfile
import subprocess
import os
from pathlib import Path


def run_cmd(cmd, cwd=None):
    return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, check=False)


def setup_test_repo():
    """Create a test git repo with AI-generated commits."""
    tmpdir = tempfile.mkdtemp()
    repo = Path(tmpdir)

    # Initialize git repo
    run_cmd(["git", "init"], cwd=repo)
    run_cmd(["git", "config", "user.name", "Test User"], cwd=repo)
    run_cmd(["git", "config", "user.email", "test@example.com"], cwd=repo)

    # Create initial commit
    (repo / "README.md").write_text("# Test Repo\n")
    run_cmd(["git", "add", "README.md"], cwd=repo)
    run_cmd(["git", "commit", "-m", "Initial commit"], cwd=repo)

    base_commit = run_cmd(["git", "rev-parse", "HEAD"], cwd=repo).stdout.strip()

    # Create a normal commit
    (repo / "normal.py").write_text("def normal():\n    return 1\n")
    run_cmd(["git", "add", "normal.py"], cwd=repo)
    run_cmd(["git", "commit", "-m", "Add normal function"], cwd=repo)

    # Create an AI-generated commit
    (repo / "ai_generated.py").write_text("def ai_func():\n    return 2\n")
    run_cmd(["git", "add", "ai_generated.py"], cwd=repo)
    run_cmd(["git", "commit", "-m", "AI-Generated: add ai function\n\nThis was generated by AI\nai-generated"], cwd=repo)

    head_commit = run_cmd(["git", "rev-parse", "HEAD"], cwd=repo).stdout.strip()

    return repo, base_commit, head_commit


def test_no_ai_commit():
    """Test with no AI-generated commits."""
    tmpdir = tempfile.mkdtemp()
    repo = Path(tmpdir)

    run_cmd(["git", "init"], cwd=repo)
    run_cmd(["git", "config", "user.name", "Test User"], cwd=repo)
    run_cmd(["git", "config", "user.email", "test@example.com"], cwd=repo)

    (repo / "README.md").write_text("# Test Repo\n")
    run_cmd(["git", "add", "README.md"], cwd=repo)
    run_cmd(["git", "commit", "-m", "Initial commit"], cwd=repo)

    base = run_cmd(["git", "rev-parse", "HEAD"], cwd=repo).stdout.strip()

    (repo / "normal.py").write_text("def normal():\n    return 1\n")
    run_cmd(["git", "add", "normal.py"], cwd=repo)
    run_cmd(["git", "commit", "-m", "Add normal function"], cwd=repo)

    head = run_cmd(["git", "rev-parse", "HEAD"], cwd=repo).stdout.strip()

    script_path = Path(__file__).parent.parent / "scripts" / "detect_ai_generated.py"
    result = run_cmd([
        "python3", str(script_path),
        "--base", base,
        "--head", head,
        "--repo", str(repo),
    ])

    print(f"Exit code: {result.returncode}")
    print(f"Stdout:\n{result.stdout}")

    # Should pass because no AI commits
    assert result.returncode == 0, "Should pass when no AI commits"
    assert "AI Review Required: False" in result.stdout
    print("✅ Test passed: No AI commits, review not required")


def test_detect_ai_commit():
    """Test detection of AI-generated commit."""
    repo, base, head = setup_test_repo()

    # Run detection script
    script_path = Path(__file__).parent.parent / "scripts" / "detect_ai_generated.py"
    result = run_cmd([
        "python3", str(script_path),
        "--base", base,
        "--head", head,
        "--repo", str(repo),
    ])

    print(f"Exit code: {result.returncode}")
    print(f"Stdout:\n{result.stdout}")
    print(f"Stderr:\n{result.stderr}")

    # Should fail because AI review not checked
    assert result.returncode == 1, "Should fail when AI review not checked"
    assert "AI Review Required: True" in result.stdout
    assert "AI Commits Found: 1" in result.stdout
    print("✅ Test passed: AI commit detected, review required")


def test_human_review_checked():
    """Test with human review checkbox checked."""
    repo, base, head = setup_test_repo()

    pr_body = """
## Description
Test PR

## AI-Generated Code Review (Mandatory)
- [x] I have reviewed ALL AI-generated code in this PR
"""

    script_path = Path(__file__).parent.parent / "scripts" / "detect_ai_generated.py"
    result = run_cmd([
        "python3", str(script_path),
        "--base", base,
        "--head", head,
        "--pr-body", pr_body,
        "--repo", str(repo),
    ])

    print(f"Exit code: {result.returncode}")
    print(f"Stdout:\n{result.stdout}")

    # Should pass because human review checked
    assert result.returncode == 0, "Should pass when human review checked"
    assert "Human Review Checked: True" in result.stdout
    assert "Review Passed: True" in result.stdout
    print("✅ Test passed: Human review checked, passes")


if __name__ == "__main__":
    test_no_ai_commit()
    test_detect_ai_commit()
    test_human_review_checked()
    print("\n🎉 All tests passed!")