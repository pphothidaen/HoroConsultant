"""
tests/test_opentelemetry_tracing.py -- Unit tests for OpenTelemetry distributed tracing (KAN-343)
Verifies W3C traceparent propagation from edge (gemini-web-bridge) into FastAPI spans.
"""

import os
import pytest
from fastapi import FastAPI
from fastapi.testclient import TestClient
from opentelemetry import trace
from project.core.observability import setup_tracing, setup_observability_middleware


def test_tracing_initialization_and_traceparent_propagation(monkeypatch):
    monkeypatch.setenv("GRAFANA_OTLP_ENDPOINT", "https://otlp-gateway-prod-ap-southeast-1.grafana.net/otlp")
    monkeypatch.setenv("OTEL_EXPORTER_OTLP_HEADERS", "Authorization=Basic dGVzdF90b2tlbg==")
    monkeypatch.setenv("OTEL_SERVICE_NAME", "HoroConsultant-Test")

    test_app = FastAPI()

    captured_traces = []

    @test_app.get("/test/trace-propagation")
    def sample_endpoint():
        current_span = trace.get_current_span()
        ctx = current_span.get_span_context()
        trace_id_hex = format(ctx.trace_id, "032x") if ctx.is_valid else None
        span_id_hex = format(ctx.span_id, "016x") if ctx.is_valid else None
        captured_traces.append((trace_id_hex, span_id_hex))
        return {"trace_id": trace_id_hex, "span_id": span_id_hex}

    setup_tracing(test_app)

    client = TestClient(test_app)

    # 1. Test request WITH W3C traceparent (simulating incoming request from gemini-web-bridge)
    incoming_trace_id = "4bf92f3577b34da6a3ce929d0e0e4736"
    incoming_parent_span = "00f067aa0ba902b7"
    w3c_header = f"00-{incoming_trace_id}-{incoming_parent_span}-01"

    res = client.get("/test/trace-propagation", headers={"traceparent": w3c_header})
    assert res.status_code == 200
    data = res.json()

    # The span inside FastAPI must adopt the exact trace_id generated by the edge worker!
    assert data["trace_id"] == incoming_trace_id
    assert data["span_id"] is not None
    assert data["span_id"] != incoming_parent_span  # It must be a new child span ID

    # 2. Test request WITHOUT traceparent (creates brand new root trace)
    res2 = client.get("/test/trace-propagation")
    assert res2.status_code == 200
    data2 = res2.json()
    assert data2["trace_id"] is not None
    assert len(data2["trace_id"]) == 32
    assert data2["trace_id"] != incoming_trace_id
