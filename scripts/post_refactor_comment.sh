#!/bin/bash
# Post Refactoring Comment Script (KAN-307 3D)
# Posts refactoring suggestions as PR comment

set -euo pipefail

REFRACTOR_FILE="${1:-refactor-report.json}"

if [[ ! -f "${REFRACTOR_FILE}" ]]; then
    echo "Refactor report not found: ${REFRACTOR_FILE}"
    exit 1
fi

if [[ -z "${GITHUB_TOKEN:-}" || -z "${GITHUB_REPOSITORY:-}" || -z "${GITHUB_PR_NUMBER:-}" ]]; then
    echo "Missing GitHub environment variables"
    exit 1
fi

echo "Posting refactoring suggestions as PR comment..."

python3 -c "
import json
import os

with open('${REFRACTOR_FILE}') as f:
    data = json.load(f)

suggestions = data.get('suggestions', [])
if not suggestions:
    print('No refactoring suggestions to post')
    exit(0)

lines = [
    '## AI Refactoring Suggestions (KAN-307 3D)',
    '',
    f'**Total Suggestions:** {len(suggestions)}',
    '',
    '### Suggestions'
]

for i, s in enumerate(suggestions[:10], 1):
    file_path = s.get('file', 'unknown')
    line = s.get('line', 0)
    severity = s.get('severity', 'info')
    category = s.get('category', 'refactor')
    suggestion = s.get('suggestion', 'No suggestion')
    lines.append(f'{i}. **[{severity.upper()}]** {file_path}:{line} ({category})')
    lines.append(f'   > {suggestion}')
    lines.append('')

if len(suggestions) > 10:
    lines.append(f'*... and {len(suggestions) - 10} more suggestions*')
    lines.append('')

lines.append('---')
lines.append('*Auto-generated by AI Refactoring Agent. Review before applying.*')

with open('refactor-comment.txt', 'w') as f:
    f.write('\n'.join(lines))
"

COMMENT_BODY=$(cat refactor-comment.txt | sed ':a;N;s/\n/\\n/g;ta' | sed 's/"/\\"/g')
gh api repos/${GITHUB_REPOSITORY}/issues/${GITHUB_PR_NUMBER}/comments -f body="${COMMENT_BODY}" || echo "Failed to post comment"

echo "Refactoring comment posted successfully"